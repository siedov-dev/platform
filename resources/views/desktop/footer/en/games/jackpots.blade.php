<p> There are two types of jackpots: fixed and progressive. A fixed jackpot is a specific fixed
    the amount of money, which is set before the start of the game and remains unchanged, regardless of the number of bets and participants.
    If no one is lucky enough to win the fixed jackpot, it will automatically continue to the next game. </P>



<p> Progressive jackpot implies a constantly growing cash prize and is formed at the expense of the participants' bets,
    tickets purchased or the number of games played.
    As in the case of the fixed jackpot, it carries over to the next game, increasing constantly if no one has won it. </p>



