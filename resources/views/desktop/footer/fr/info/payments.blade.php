<h1 class = "page-title"> Anti Money Laundering Policy </h1>
<p> The company will take measures to prevent the fact of money laundering in its activities, for
    identifying areas where money laundering may occur and compliance with laws and regulations
    requirements, in particular the process for reporting actual or suspected money laundering cases
    Money Laundering Officer (Financial Monitoring Officer).
    It is the responsibility of each employee to be vigilant and take immediate action in all suspicious cases. </p>


<ol>
    <li> <b> Introduction </b> </li>
</ol>


<p> 1.1. The Provisions of the Proceeds of Crime Act, the Anti-Terrorism and Money Laundering Act 2007,
    impose obligations on the Company and its employees in relation to alleged money laundering, the key points of which are: </p>
<ul>
    <li style = "font-weight: 400;"> <p> Alleged money laundering reporting and detection. </p> </li>
    <li style = "font-weight: 400;"> <p> Employees must be vigilant for signs of money laundering. </p> </li>
    <li style = "font-weight: 400;"> <p> Any employee who suspects money laundering activity must immediately
            report this to the Anti-Money Laundering Officer. </p> </li>
    <li style = "font-weight: 400;"> <p> Anti-money laundering regulations are complex and detailed, and if any
            If you have any doubts about the policy requirements, please contact your line manager for more information. </p> </li>
</ul>

<ol start = "2">
    <li> <b> Policy </b> </li>
</ol>


<p> 2.1. The policy applies to all players and sets out procedures for reporting suspicious activity on
    money laundering in order to reduce potential criminal activity. The policy sets out the procedures that
    will help the Company comply with its legal obligations. </p>

<p> 2.2. This Policy has the same effect as the Suspected Misconduct Policy.
    Anti-Fraud and Anti-Corruption Policy and Money Management System - A Guide to Money Laundering. </p>

<p> 2.3. Failure by an employee to comply with the procedures established under this policy may result in
    disciplinary action in accordance with the Company's disciplinary policy procedures. </p>

<p> 2.4. A member's failure to comply with the procedures established under this policy will be communicated to the supervisor for
    further action, such as a possible report to the Standards Committee. </p>


<ol start = "3">
    <li> <b> What is money laundering? </b> </li>
</ol>


<p> 3.1. Money laundering is a used term that refers to the proceeds of crime.
    or terrorist means. The following activities are defined as acts of money laundering: </p>
<ul>
    <li style = "font-weight: 400;"> <p> To enter into or participate in an agreement that you think or suspect may
            help in the acquisition, preservation, use or control of property acquired by criminal means
            or on behalf of another person (Section РОСА 328) </p> </li>
    <li style = "font-weight: 400;"> <p> Acquisition, use or possession of criminally acquired property </p> </li>
</ul>


<p> These are the primary anti-money laundering actions, also identified two Tuesday offenses that
    refer to non-disclosure of any of the three primary actions and disclosure of classified information.
    Disclosure of classified information is an act in which someone informs a person or persons,
    involved or suspected of being involved in money laundering activities in a manner that makes them less likely to be investigated. </p>



<p> 3.2. While the Company's risk of violating the law is considered low, employees in all areas
    must be aware that they are potentially vulnerable to money laundering activities.
    It is important that employees are aware of their responsibility to notify any suspicions of
    money laundering activities as detailed under this policy (see reporting).
    All employees are responsible for acting promptly and reporting any suspicions of money laundering
    the anti-money laundering inspector to prevent any violations of the law that may
    lead to serious criminal penalties. </p>


<ol start = "4">
    <li> <b> Anti-Money Laundering Officer (Financial Monitoring Officer) </b> </li>
</ol>


<p> 4.1 The officer designated to obtain information on money laundering activities is the
    financial monitoring. The Anti-Money Laundering Officer confidentially processes all received
    information and makes decisions on the provision of activities to all bodies in the appropriate manner, all reports
    last for five years. </p>


<ol start = "5">
    <li> <b> Reporting </b> </li>
</ol>


<p> 5.1. Any employee who suspects money laundering activity is required to promptly report their
    suspicions to the anti-money laundering inspector using the attached form, after receiving the report
    the anti-money laundering inspector may contact you directly to discuss the contents of the report
    as needed. </p>

<p> 5.2. After submitting the report to the Anti-Money Laundering Officer, no other contact information
    the suspect in money laundering has not been reported. No other steps in any transaction regarding the intended
    money laundering activities are not carried out without the approval of the anti-money laundering inspector.
    For example, if repeatedly specified overpayments are credited to a specific account, get a recommendation from
    an anti-money laundering inspector before the amounts are returned as a Company bank check. </p>

<p> 5.3. It is prohibited to disclose information to other persons who have indicated suspicions of money laundering activities.
    Any employee providing information should not discuss the issue with others or mark in a document,
    that the report was forwarded to the AML inspector, as this could lead to the disclosure of information to the suspect. </p>

<p> 5.4. The Anti-Money Laundering Officer promptly evaluates any Disclosure Report to determine whether
    whether to report to all government agencies. </p>



<p> 5.5. The inspector for combating money laundering, if necessary, will immediately inform the state
    body in a standard electronic form in the prescribed manner. </p>

<p> 5.6. Failure to report disclosure to the Organized Crime Agency (SOCA) is considered criminal
    a crime without a reasonable basis. All disclosures will be archived for five years. </p>


<ol start = "6">
    <li> <b> Customer due diligence measures </b> </li>
</ol>


<p> 6.1. Particular care must be taken when the Company carries out regulated activities,
    known as customer due diligence measures, such as cash management activities,
    collecting a service fee as a business or user other than a UK government agency.
    According to the nature or strong guidelines for a regulated business, you will know if your
    responsibilities include regulated activities. </p>



<p> 6.2. When using customer due diligence (CDD) measures, you are required to look for proof of identity, for example: </p>
<ul>
    <li style = "font-weight: 400;"> <p> Check the business website to confirm their legal address </p> </li>
    <li style = "font-weight: 400;"> <p> Search online with Companies House to confirm character
            business and the personality of directors. </p> </li>
    <li style = "font-weight: 400;"> <p> Find evidence from the key contact of their personal identity as recommended
            on customer identification (Recommendations are given in section seven of the company's procedures for cashing). </p>
</ul>
<p> 6.3 Identification must be retained for five years after the termination of the business relationship. </p>


