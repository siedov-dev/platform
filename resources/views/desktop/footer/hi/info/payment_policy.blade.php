<p>आपको हर समय केवल खाते/सिस्टम से और/या अपने नाम से पंजीकृत भुगतान कार्ड का उपयोग करके जमा करना आवश्यक है।</p>
<p>भुगतान उसी खाते/भुगतान कार्ड पर भेजा जाता है, जिससे जमा किया गया था.</p>






