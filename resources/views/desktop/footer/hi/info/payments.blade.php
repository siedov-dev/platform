    <li> <b> मार्गदर्शन और प्रशिक्षण </b> </li>
</ol>


<p> 7.1. कंपनी सभी कर्मचारियों को कंपनी पर और स्वयं पर लगाई गई आवश्यकताओं और दायित्वों के बारे में सूचित करती है
    एक व्यक्ति के रूप में, धन शोधन विरोधी कानून के अनुसार, और लक्षित प्रदान करता है
    मनी लॉन्ड्रिंग का सामना करने की सबसे अधिक संभावना वाले लोगों के लिए प्रशिक्षण.</p>
