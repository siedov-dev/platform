<p class = "info__title"> How to withdraw money </p>
<p>
    If you have activated the bonus and the conditions for wagering it have not yet been met, then you will not be able to pay anything. <br/>
    Top right, click on your nickname. <br/>
    You will be taken to “My Profile”. Select the "Withdrawal" section, enter the card number, full name of the owner where you want to withdraw money. <br/>
    If your status is above the cabin boy, the payment is made automatically up to 5000 rubles. or UAH 2500, everything above the indicated amount is moderated. <br/>
    Moderation can take up to 24 hours from the moment of application.
</p>

