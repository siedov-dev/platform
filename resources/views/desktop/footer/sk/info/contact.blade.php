<h1 class = "open-bonus-heading"> Anti-money laundering policy </h1>

<p> The Company will take measures to prevent the fact of money laundering in its activities,
    to identify areas where money laundering may occur and to comply with legal and regulatory requirements,
    in particular the process of reporting actual or suspected cases of money laundering to the inspector
    Anti-Money Laundering Officer (Financial Monitoring Officer). The responsibility of each employee
    is a manifestation of vigilance, and immediate action in all suspicious cases </p>

<p class = "info__title"> Introduction </p>

<p> 1.1. Provisions of the Proceeds of Crime Act, the Anti-Terrorism and Laundering Act
    money in the 2007 edition impose obligations on the Company and its employees in relation to the alleged
    money laundering, the key points of which are: </p>

<p class = "info__important"> Alleged money laundering reporting and detection. </p>

<p class = "info__important"> Employees must be vigilant for signs of money laundering. </p>

<p class = "info__important"> Any employee who suspects money laundering activity must
    notify the Anti-Money Laundering Officer immediately. </p>

<p class = "info__important"> Anti-money laundering regulations are complex and detailed, and
    If you are in any doubt about a policy requirement, please request additional
    information from the direct management. </p>

<p class = "info__title"> Policy </p>

<p> 2.1. The policy applies to all players and sets out procedures for reporting
    suspicious money laundering activities in order to reduce potential criminal activity.
    The policy sets out procedures that will help the Company comply with its legal obligations. </p>

<p> 2.2. This Policy has the same effect as the Suspected Commitment Notification Policy.
    Misconduct, Anti-Fraud and Anti-Corruption Policy and Money Management System
    funds - a guide to money laundering. </p>

<p> 2.3. Failure of an employee to comply with the procedures established under this policy,
    may result in disciplinary action in accordance with the Company's disciplinary policy procedures. </p>

<p> 2.4. Member's failure to comply with the procedures established under this policy,
    will be forwarded to the supervisor for further action, such as a possible report to the Standards Committee. </p>

<p class = "info__title"> What is money laundering? </p>


<p> 3.1. Money laundering is a used term that refers to crimes related to
    proceeds of crime or terrorist funds. The following activities are defined as acts of money laundering: </p>

<p class = "info__important"> To conclude or participate in an agreement that you think or suspect
    can assist in the acquisition, preservation, use or control of criminally acquired property
    or on behalf of another person (Section РОСА 328) </p>

<p class = "info__important"> Acquisition, use or possession of criminally acquired property </p>


<p class = "info__important"> These are the primary anti-money laundering actions, also two Tuesday
    offenses that relate to non-disclosure of any of the three primary actions and disclosure of a secret
    information. Disclosure of classified information is an act in which someone informs a person or
    persons involved in or suspected of money laundering activities in a manner that reduces the likelihood of their
    investigation. </p>

<p> 3.2. While the Company's risk of violating the law is considered low,
    employees in all areas have a responsibility to be aware that they are potentially vulnerable to money laundering activities.
    It is important that employees are aware of their responsibility to notify any suspicions of
    money laundering activities as detailed under this policy (see reporting). All employees
    have the responsibility to act promptly and report any suspicions of money laundering to the
    anti-money laundering to prevent any violations of the law that may lead to
    to serious criminal penalties. </p>

<p class = "info__title"> Anti-Money Laundering Officer (Financial Monitoring Officer) </p>

<p> 4.1 By the officer assigned to receive information on money laundering activities,
    is the Financial Monitoring Officer. Anti-money laundering inspector confidential
    processes all the information received and makes decisions on the provision of activities to all bodies in
    the corresponding order, all reports are retained for five years. </p>

<p class = "info__title"> Reporting </p>

<p> 5.1. Any employee who suspects money laundering activity is required to
    immediately report your suspicions to the anti-money laundering inspector using the attached
    the form, after receiving the report, the anti-money laundering inspector can contact you directly,
    to discuss the contents of the report as needed. </p>

<p> 5.2. Once the report has been submitted to the Anti-Money Laundering Officer, no
    other contact details of the suspect in money laundering were not disclosed. No other steps in any transaction
    regarding the alleged money laundering activity is not carried out without the approval of the anti-counterfeiting officer
    money laundering. For example, if the repeatedly specified monetary overpayments are credited to a specific account, you will receive
    recommendations from the AML inspector before the amounts are returned as
    Company bank check. </p>

<p> 5.3. It is prohibited to disclose information to other persons who have indicated suspicions of
    money laundering activities. Any employee providing information should not discuss the issue with
    by other persons or indicate in the document that the report has been sent to the anti-money laundering inspector,
    as this could lead to the disclosure of information to the suspect. </p>

<p> 5.4. The Anti-Money Laundering Officer promptly evaluates any Report on
    disclosure to determine whether to report to all government agencies. </p>

<p> 5.5. Anti-money laundering inspector, if necessary, immediately
    will notify the government agency about it by standard electronic form in the prescribed manner. </p>

<p> 5.6. Refusal to report disclosure to the Organized Crime Agency
    (SOCA) is considered a criminal offense without a reasonable basis. All disclosures will be
    kept in the archive for five years. </p>

