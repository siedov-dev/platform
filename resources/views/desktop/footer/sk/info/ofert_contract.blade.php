<p class="info__title">28. UDALOSTI, KTORÉ NIE SÚ POD NAŠOU KONTROLOU</p>
<p>28.1. Krakencassino nezodpovedá za žiadne zlyhanie alebo oneskorenie pri plnení akéhokoľvek z našich
     povinnosti vyplývajúce z Podmienok používania, ktoré sú spôsobené udalosťami, ktoré nie sú pod našou kontrolou (vrátane, ale
     nie je obmedzená akýmikoľvek poruchami telekomunikačnej siete, výpadkami napájania, poruchami počítača tretích strán
     (alebo iné) vybavenie, požiar, blesk, výbuch, povodeň, nepriaznivé počasie, priemyselné spory alebo výluky,
     teroristická činnosť a činy vlády alebo iných príslušných orgánov. Tieto okolnosti sa vzťahujú na a
     "Udalosť vyššej moci". Nie je možné ich overiť a nebolo možné ich predvídať.</p>
<p>28.2. Naša prevádzka môže byť pozastavená na obdobie pokračovania udalosti vyššej moci. My z našej strany
     vynaloží všetko primerané úsilie na vyriešenie problému a nájde riešenie, ktoré nám umožní vykonať naše
     povinnosti napriek udalosti vyššej moci.</p>

<p class="info__title">29. VZDANIE SA</p>
<p>29.1. Používateľ splní svoje záväzky voči nám, aj keď:</p>

<p class="info__important">- netrváme na prísnom plnení akýchkoľvek povinností používateľa;</p>
<p class="info__important">- nemáme možnosť uplatniť žiadne práva ani opravné prostriedky, ktorými sme
     oprávnený (nepredstavuje to vzdanie sa takýchto práv alebo opravných prostriedkov).</p>

<p>29.2. Akékoľvek odmietnutie dodržiavať niektoré z pravidiel a ustanovení Podmienok používania nie je platné, pokiaľ nie je platné
     popis výslovne uvádza, že implementácia tohto pravidla alebo ustanovenia je voliteľná.</p>
<p>29.3. Žiadne zrieknutie sa ktoréhokoľvek z ustanovení Podmienok používania z našej strany nebude účinné, pokiaľ to nie je výslovne uvedené
     uvedené ako zrieknutie sa práva a je vám oznámené písomne.</p>

<p class="info__title">30. ODDELITEĽNOSŤ</p>
<p>30.1. Ak ktorýkoľvek príslušný orgán určí ktorúkoľvek z Podmienok používania ako neplatnú, nezákonnú alebo nevymáhateľnú,
     budú oddelené od zostávajúcich zmluvných podmienok a ustanovení, ktoré budú naďalej platné v plnom rozsahu povolenom zákonom.</p>
<p>30.2. V takom prípade sa časť, ktorá sa považuje za neplatnú alebo nevymáhateľnú, zmení v súlade s platnou legislatívou.</p>

<p class="info__title">31. CELÁ ZMLUVA</p>
<p>31.1. Podmienky používania a akékoľvek iné dokumenty, na ktoré sa v nich výslovne odkazuje, tvoria celok
     dohoda medzi vami a nami. Nahrádzajú akúkoľvek predchádzajúcu dohodu, porozumenie alebo dojednanie medzi vami a nami (hovorené alebo písomné).</p>
<p>31.2. Spoločnosť a používateľ sa dohodli, že sa nespoliehajú na iné vyhlásenie, záväzok alebo prísľub, ktorý
     boli poskytnuté druhou stranou alebo implicitné z čohokoľvek, čo bolo povedané alebo napísané pri rokovaniach medzi nami, ak nie je výslovne uvedené inak
     uvedené v podmienkach používania.</p></p>
<p>32. PRÁVA TRETÍCH STRÁN</p>
<p>32.1. S výnimkou spoločností skupiny Prevádzkovateľa, pokiaľ tieto Podmienky používania výslovne neuvádzajú inak:</p>

<p class="info__important">- strana alebo osoba, ktorá nemusí dodržiavať tieto Podmienky používania, nemá právo vymáhať
     ktorúkoľvek z podmienok podľa zmlúv (právo tretích strán);</p>
<p class="info__important">- ak je uvedené, že osoba alebo strana, ktorá nie je zmluvnou stranou týchto Podmienok používania,
     má právo vymáhať ktorúkoľvek zo svojich podmienok podľa zmlúv o právach tretích strán, vyhradzujeme si právo
     zrušiť alebo zmeniť tieto Podmienky používania podľa vlastného uváženia (a akékoľvek iné dokumenty, ktoré ste uzavreli v súlade s
     alebo v súvislosti s ním) bez vášho súhlasu alebo súhlasu danej osoby/strany.</p>




