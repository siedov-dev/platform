<ol start="5">
     <li><b>Reporting</b></li>
</ol>


<p>5.1. Any employee who suspects money laundering activity is required to immediately report their
     suspicions to the money laundering inspector using the attached form after receiving the report
     the money laundering officer can contact you directly to discuss the content of the report
     as needed.</p>

<p>5.2. After submitting the report to the money laundering inspector, no other contact information
     no money laundering suspect has been reported. No other steps in any transaction regarding the proposed
     money laundering activities are not carried out without the approval of the money laundering inspector.
     For example, if repeated cash overpayments go to a specific account, get referrals from
     money laundering inspector before the amounts are returned as the Company's bank check.</p>

<p>5.3. It is prohibited to disclose information to other persons who have indicated suspicions of money laundering activities.
     Any employee who provides information should not discuss the issue with others or note in the document,
     that the report was sent to the money laundering inspector, as this may lead to disclosure of information to the suspect.</p>

<p>5.4. The Money Laundering Inspector shall promptly evaluate any Disclosure Report to determine whether
     whether to report to all public authorities.</p>



<p>5.5. The Money Laundering Inspector, if necessary, will immediately notify the state
     body in a standard electronic form in the prescribed manner.</p>

<p>5.6. Failure to report disclosure to the Organized Crime Agency (SOCA) is considered a criminal offense
     crime without reason. All disclosures will be archived for five years.</p>


