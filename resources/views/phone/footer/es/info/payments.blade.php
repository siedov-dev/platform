     In accordance with the nature or rigid guidelines for a regulated business, you will know if your
     responsibilities include regulated activities.</p>



<p>6.2. When using Customer Due Diligence (CDD) measures, you are required to look for evidence of identity, for example:</p>
<ul>
     <li style="font-weight: 400;"><p>Check the business website to confirm their legal address</p></li>
     <li style="font-weight: 400;"><p>Do an online search with Companies House to confirm character
             business and personality of directors.</p></li>
     <li style="font-weight: 400;"><p>Find evidence from a key contact of their personal identity as recommended
             on identification of customers (Recommendations are given in section seven of the Procedure for clearing a company).</p>
</ul>
<p>6.3 Identification must be retained for five years after the end of the business relationship.</p>


