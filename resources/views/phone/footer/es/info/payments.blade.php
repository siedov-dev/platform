<h1 class="page-title">Money Laundering Policy</h1>
<p>The Company will take measures to prevent the fact of money laundering in its activities, in order to
     identify areas where money laundering may occur and comply with legal and regulatory
     requirements, in particular the reporting process on actual or suspected cases of money laundering
     money laundering inspector (financial monitoring officer).
     It is the responsibility of every employee to be vigilant and take immediate action in all suspicious cases</p>


