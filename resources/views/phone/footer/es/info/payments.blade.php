<ol start="2">
     <li><b>Politics</b></li>
</ol>


<p>2.1. The policy applies to all players and establishes procedures for reporting suspicious activity on
     money laundering in order to reduce potential criminal activity. The policy establishes procedures that
     will help the Company meet its legal obligations.</p>

<p>2.2. The Policy has the same effect as the Suspicion of Misconduct Notification Policy,
     Anti-Fraud and Anti-Corruption Policy and Money Management System - A Guide to Money Laundering.</p>

<p>2.3. An employee's failure to comply with the procedures established under this policy may result in
     disciplinary action in accordance with the procedures of the Company's disciplinary policy.</p>

<p>2.4. A member's failure to comply with the procedures established under this policy will be referred to a supervisor for
     further action, such as a possible report to the Standards Committee.</p>


<ol start="3">
     <li><b>What is money laundering?</b></li>
</ol>


<p>3.1. Money laundering is a term used to refer to crimes involving the proceeds of crime.
     or terrorist means. The following activities are defined as acts of money laundering:</p>
<ul>
     <li style="font-weight: 400;"><p>To enter into or participate in an arrangement that you think or suspect may
             assist in the acquisition, preservation, use or control of criminally acquired property
             or on behalf of another person (POCA Section 328)</p></li>
     <li style="font-weight: 400;"><p>Acquiring, using or possessing criminally acquired property</p></li>
</ul>


<p>These are primary anti-money laundering actions, two secondary offenses are also identified, which
     refer to non-disclosure of any of the three primary actions and disclosure of classified information.
     Disclosure of classified information is an act in which someone informs a person or persons
     involved in or suspected of money laundering activities in a manner that reduces the likelihood of them being investigated.</p>



<p>3.2. While the Company's risk of violations of the law is considered low, employees in all areas
     are required to know that they could potentially be subject to money laundering activities.
     It is important that employees are aware of their responsibility to report any suspicion of
     money laundering activities as detailed under this policy (see reporting).
     All employees have a responsibility to act promptly and report any suspicion of money laundering
     money laundering inspector to prevent any violations of the law that may
     lead to severe criminal penalties.</p>


