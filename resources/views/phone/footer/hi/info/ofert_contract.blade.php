    इस तरह के संशोधन के समय पहले से ही प्रगति पर है। हम समय-समय पर आपकी पहुंच को इसके कुछ हिस्सों तक सीमित कर सकते हैं
    वेबसाइट के रखरखाव के लिए / उसमें परिवर्तन करने के लिए / वेबसाइट द्वारा प्रदान किए गए किसी भी गेम या उत्पाद में संशोधन करने के लिए वेबसाइट।</p>

<p class="info__title">17. तृतीय-पक्ष सॉफ़्टवेयर</p>
<p>१७.१. वेबसाइट का उपयोग करने के लिए आपके एक्सेस डिवाइस को डाउनलोड और इंस्टॉल करने के लिए सॉफ़्टवेयर की आवश्यकता हो सकती है
    आपके लिए संभव है। सॉफ़्टवेयर में शामिल हो सकते हैं (लेकिन यह सीमित नहीं है): एक्सेस डिवाइस एप्लिकेशन, हमारा डाउनलोड कैसीनो
    उत्पाद, कोई प्रचार, विपणन या सुविधा अनुप्रयोग, उत्पाद और सॉफ़्टवेयर.</p>
<p>17.2. ऐसी परिस्थितियों में, आपको स्वामी या लाइसेंसकर्ता के साथ एक अलग अनुबंध करने की आवश्यकता हो सकती है
    आपके द्वारा उसी के उपयोग के संबंध में (एक "तृतीय-पक्ष सॉफ़्टवेयर अनुबंध")। उस स्थिति में, यदि
    तृतीय-पक्ष अनुबंध उपयोग की शर्तों का उल्लंघन करता है, उपयोग की शर्तें प्रबल होंगी।</p>
<p>१७.३. आप यह सुनिश्चित करने के लिए ज़िम्मेदार हैं कि कोई भी सॉफ़्टवेयर आपके एक्सेस डिवाइस पर एक तरीके से डाउनलोड किया गया है
    अपने स्वयं के एक्सेस डिवाइस विशिष्ट सेट-अप के साथ संगत। हम आपके डिवाइस को नुकसान पहुंचाने के लिए ज़िम्मेदार नहीं हैं,
    जो किसी तृतीय-पक्ष सॉफ़्टवेयर को डाउनलोड करने के कारण हो सकता है।</p>
<p>१७.४. कोई भी एप्लिकेशन, जो आपके एक्सेस डिवाइस पर डाउनलोड या इंस्टॉल किया गया है, न केवल इसकी पुष्टि करेगा
    आपके और इस एप्लिकेशन के प्रदाता के बीच समझौता, लेकिन यह आपके और Krakencassino के बीच समझौते की पुष्टि भी करेगा।</p>

<p class="info__title">18. आईटी विफलता</p>
<p>यदि सॉफ़्टवेयर या हार्डवेयर में कोई समस्या है, जिसका उपयोग हम सेवाएं प्रदान करने के लिए करते हैं, तो हम सब कुछ करेंगे
