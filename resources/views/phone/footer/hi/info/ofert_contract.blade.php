    खेल प्रक्रिया में रुकावट (उस मामले में, जब आप अपनी प्रगति खो देते हैं और खेल को ठीक उसी स्थिति से फिर से शुरू नहीं किया जा सकता है), हम प्रत्येक मामले को व्यक्तिगत रूप से और उचित तरीके से व्यवहार करेंगे (उपयोगकर्ता खाते पर शेष राशि को बहाल करने की संभावना सहित, अंतिम दांव या खेल की वसूली, आदि)। लेकिन अगर हमारे पास यह विश्वास करने का कोई कारण है कि आप लाभ या हानि प्राप्त करने के लिए जानबूझकर हमारे या किसी तीसरे पक्ष के सॉफ़्टवेयर में तकनीकी त्रुटि, खामियों या त्रुटि का उपयोग करते हैं, जिसका उपयोग आपने सेवाओं के संबंध में किया है, तो Krakencassino कोई जिम्मेदारी नहीं लेता है और खिलाड़ियों को क्षतिपूर्ति या धनवापसी नहीं करने का अधिकार सुरक्षित रखता है.</p>

<p class="info__title">19. त्रुटियां और चूक</p>
