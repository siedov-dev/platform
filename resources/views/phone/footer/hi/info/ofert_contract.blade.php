    विवरण स्पष्ट रूप से इंगित करता है कि इस नियम या प्रावधान का कार्यान्वयन वैकल्पिक है।</p>
<p>29.3। उपयोग की शर्तों के किसी भी प्रावधान से हमारे द्वारा कोई छूट तब तक प्रभावी नहीं होगी जब तक कि यह स्पष्ट रूप से न हो
    एक छूट के रूप में कहा गया है और आपको लिखित रूप में सूचित किया गया है।</p>

<p class="info__title">30. गंभीरता</p>
<p>३०.१. यदि कोई सक्षम प्राधिकारी किसी भी उपयोग की शर्तों को अमान्य, गैरकानूनी या अप्रवर्तनीय के रूप में निर्धारित करता है,
    उन्हें शेष नियमों, शर्तों और प्रावधानों से अलग कर दिया जाएगा जो कानून द्वारा अनुमत पूर्ण सीमा तक वैध बने रहेंगे।</p>
<p>३०.२. उस मामले में, अमान्य या अप्रवर्तनीय समझा जाने वाला हिस्सा वर्तमान कानून के अनुसार बदल दिया जाएगा.</p>

<p class="info__title">31. संपूर्ण अनुबंध</p>
<p>३१.१. उपयोग की शर्तें और कोई भी अन्य दस्तावेज, जिनका स्पष्ट रूप से उनमें उल्लेख किया गया था, संपूर्ण का गठन करते हैं
    आपके और हमारे बीच समझौता। वे आपके और हमारे बीच (बोली या लिखित) किसी भी पूर्व समझौते, समझ या व्यवस्था को प्रतिस्थापित करते हैं।</p>
<p>३१.२. कंपनी और उपयोगकर्ता सहमत हैं कि वे अन्य प्रतिनिधित्व, उपक्रम या वादे पर भरोसा नहीं करते हैं, जो
    दूसरे द्वारा दिए गए थे या हमारे बीच बातचीत में कही गई या लिखी गई किसी बात से निहित थे, सिवाय स्पष्ट रूप से
    उपयोग की शर्तों में कहा गया है।</p></p>
<p>32. तृतीय पक्ष अधिकार</p>
<p>३२.१. ऑपरेटर की समूह कंपनियों के अपवाद के साथ, जब तक कि ये उपयोग की शर्तें स्पष्ट रूप से अन्यथा न बताएं:</p>

<p class="info__important">- पार्टी या व्यक्ति, जिसे इन उपयोग की शर्तों का पालन नहीं करना है, उसे लागू करने का कोई अधिकार नहीं है
    अनुबंधों के अंतर्गत कोई भी शर्त (तृतीय पक्ष का अधिकार);</p>
<p class="info__important">- यदि यह उल्लेख किया गया है कि एक व्यक्ति या पार्टी, जो इन उपयोग की शर्तों का पक्ष नहीं है,
    तीसरे पक्ष के अधिकारों के अनुबंधों के अनुसार इसकी किसी भी शर्त को लागू करने का अधिकार है, हम अधिकार सुरक्षित रखते हैं
    हमारे अपने विवेक पर उपयोग की इन शर्तों को रद्द या परिवर्तित करें (और कोई भी अन्य दस्तावेज़, जिसे आपने अनुसरण में दर्ज किया है
    को या उसके संबंध में) आपकी सहमति के बिना या उस व्यक्ति/पार्टी की सहमति के बिना.</p>




