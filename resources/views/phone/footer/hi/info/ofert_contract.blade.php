<p class="info__title">15. सेवाओं तक पहुंच और उनका उपयोग</p>
<p>15.1. आप इंटरनेट कनेक्शन की गुणवत्ता और गति की जिम्मेदारी लेते हैं, जो आपको प्रदान की जाती है।
    इसके अलावा, आप दूरसंचार नेटवर्क की गुणवत्ता, अपने सभी एक्सेस उपकरणों और सभी के लिए जिम्मेदार हैं
    उपकरण, जिन्हें आपको सेवाओं तक पहुंच प्राप्त करने के लिए उपयोग करने की आवश्यकता है। हम किसी भी तरह से उत्तरदायी नहीं होंगे
    इंटरनेट कनेक्शन से जुड़े तकनीकी मुद्दों के परिणामस्वरूप आपको हुए किसी भी नुकसान के लिए,
    दूरसंचार नेटवर्क, आपका एक्सेस डिवाइस या अन्य उपकरण जिनका उपयोग आपने सेवाओं तक पहुंच प्राप्त करने के लिए किया था।
    Krakencassino जिम्मेदार नहीं है और सेवाओं की संगतता की गारंटी नहीं देता है, जो हम प्रदान करते हैं, किसी के साथ
    विशेष रूप से तृतीय-पक्ष सॉफ़्टवेयर या हार्डवेयर (किसी भी बाहरी प्रोग्राम सहित, खेल की भविष्यवाणी के लिए उपयोग किया जाता है
    परिणाम या उन पर प्रभाव)।</p>
<p>15.2. Krakencassino द्वारा प्रदान की गई सेवाओं का उपयोग, एक नस्लवादी की मानहानिकारक, अपमानजनक, अश्लील, गैरकानूनी, में,
    सेक्सिस्ट या अन्य भेदभावपूर्ण प्रकृति सख्त वर्जित है। उपयोगकर्ताओं को भी किसी भी अपमानजनक या आक्रामक का उपयोग नहीं करना चाहिए
    भाषा या चित्र, किसी अन्य व्यक्ति को शपथ दिलाना, धमकी देना, परेशान करना या गाली देना (अन्य उपयोगकर्ताओं और क्रैकेनकैसिनो प्रशासन सहित).</p>

<p>15.3. आप सहमत हैं कि आप वेबसाइट का उपयोग केवल व्यक्तिगत मनोरंजन के लिए करेंगे। पहुंच प्रदान करना निषिद्ध है
    या वेबसाइट या उसके किसी भी हिस्से को हमारी सहमति के बिना किसी भी रूप में पुन: पेश करें, जिसमें लिंक बनाना भी शामिल है।</p>

<p>१५.४. आप वेबसाइट पर अपलोड की गई किसी भी सामग्री के लिए जिम्मेदार हैं। यदि आप इस तरह की कोई भी सामग्री पर अपलोड करते हैं
    वेबसाइट, आप गारंटी देते हैं कि:</p>

<p class="info__important">- आपने सभी आवश्यक अनुमोदन, सहमति, लाइसेंस और अनुमतियां प्राप्त कर ली हैं, जो कि
    इस सामग्री को प्राप्त करने और इसे वेबसाइट पर अपलोड करने के लिए आवश्यक;</p>
<p class="info__important">- इस सामग्री को पुन: प्रस्तुत करने से कॉपीराइट, ट्रेडमार्क, गोपनीय का उल्लंघन नहीं होगा
    किसी तीसरे पक्ष की जानकारी या कोई अन्य बौद्धिक संपदा अधिकार;</p>
<p class="info__important">- अपलोड की गई सामग्री में कोई भी सामग्री शामिल नहीं होगी, जो अनुच्छेद का उल्लंघन करेगी
    12.2 और पैराग्राफ 12.3;</p>
<p class="info__important">- अपलोड की गई सामग्री सभी कानूनों और विनियमों का अनुपालन करती है (जिसमें, विशेष रूप से,
