<h1>Что такое джекпот?</h1>
<p>Впервые слово «джекпот» было применено два столетия назад в покере, хотя смысл этого слова возник гораздо ранее.
Дословно оно переводится с английского языка как «джек» – это «валет» и «пот» – это «банк».
В последнее время это слово обрело более широкое значения и употребляется во всевозможных азартных играх.
Сейчас под словом «джекпот» понимают самый большой выигрыш или куш.</p>

<p>Джекпот бывает двух видов: фиксированный и прогрессивный. Фиксированный джекпот — это определенная фиксированная
сума денег, которая устанавливается до начала игры и остаётся неизменной, несмотря на количество ставок и участников.
Если никому не повезло выиграть фиксированный джекпот, он автоматически переходит на следующую игру.</P>

<p>Прогрессивный джекпот подразумевает собой постоянно растущий денежный приз и формируется за счёт ставок участников,
купленных билетов или количества сыгранных игр.
Как и в случае с фиксированным джекпотом, он переносится на следующую игру постоянно увеличиваясь, если его никто не выиграл.</p>

<p>В наше время слово джекпот применяется, если не во всех, то в большинстве азартных игр. Таких как лотереи,
интернет-казино, игровые автоматы, тотализаторы, рулетки, букмекерские конторы, карточные игры.
Джекпот стал самим желанным выигрышем для миллионов игроков, вершиной удачи и пределом мечтаний. И это не удивительно,
поскольку джекпот является максимальной суммой, разыгрываемой в игре.</p>

