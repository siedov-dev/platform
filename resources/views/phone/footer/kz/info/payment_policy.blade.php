<p class="info__important-1"> Политика отмены </p>

<p> Выплаты производятся круглосуточно, от нескольких минут до 24 часов с момента подачи заявки на вывод.
<p> От вас всегда требуется вносить депозиты исключительно из учетной записи / системы и / или с помощью платежной карты, зарегистрированной на ваше имя. </p>
<p> Платежи отправляются на тот же счет / платежную карту, с которой был сделан депозит. </p>






