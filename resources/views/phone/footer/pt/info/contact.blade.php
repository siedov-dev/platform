<p class="info__title"> What is money laundering?</p>


<p>3.1. Money laundering is a term used to refer to crimes related to
     proceeds of crime or terrorist funds. The following activities are defined as acts of money laundering:</p>

<p class="info__important">To enter into or participate in an arrangement that you think or suspect
     may assist in the acquisition, preservation, use or control of criminally acquired property
     or on behalf of another person (Section ROSA 328)</p>

<p class="info__important">Acquiring, using or possessing criminally acquired property</p>


<p class="info__important">These are primary anti-money laundering activities, two secondary activities are also defined
     offenses that relate to failure to disclose any of the three primary acts and disclosure of secret
     information. Disclosure of classified information is an act in which someone informs a person or
     persons involved in or suspected of money laundering activities in a manner that reduces the likelihood of their
     investigation.</p>

<p>3.2. While the Company's risk of violations of the law is considered low,
     employees in all areas have a responsibility to be aware that they may potentially be exposed to money laundering activities.
     It is important that employees are aware of their responsibility to report any suspicion of
     money laundering activities as detailed under this policy (see reporting). All employees
     have a responsibility to act promptly and report any suspicion of money laundering to the
     anti-money laundering to prevent any violations of the law that could lead to
     to serious criminal penalties.</p>

