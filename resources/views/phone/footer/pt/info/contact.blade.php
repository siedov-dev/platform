<h1 class="open-bonus-heading">Money Laundering Policy</h1>

<p>The Company will take measures to prevent the fact of money laundering in its activities,
     to identify areas where money laundering may occur and to comply with legal and regulatory requirements,
     in particular the process of reporting actual or suspected cases of money laundering to the inspector
     Anti-Money Laundering Officer (Financial Monitoring Officer). The responsibility of each employee
     is a manifestation of vigilance, and instant action in all suspicious cases</p>

<p class="info__title">Introduction</p>

<p>1.1. Proceeds of Crime Act, Anti-Terrorism and Money Laundering Act
     money as amended in 2007, impose obligations on the Company and its employees in relation to the alleged
     money laundering, the key points of which are:</p>

<p class="info__important">Reporting and detecting alleged money laundering.</p>

<p class="info__important">Employees are required to be vigilant for signs of money laundering.</p>

<p class="info__important">Any employee who suspects money laundering activity is required to
     inform the money laundering inspector immediately.</p>

<p class="info__important">The anti-money laundering regulations are complex and detailed, and
