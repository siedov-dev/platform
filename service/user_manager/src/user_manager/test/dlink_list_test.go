package test

import (
	"fmt"
	"testing"
	"user-manager/pkg/gstructs"
)

func TestDlinkList(t *testing.T) {
	dl := new(gstructs.DLinkedList[int])
	fmt.Println(dl)
	dl.Push(1)
	fmt.Println(dl)
	dl.Push(2)
	fmt.Println(dl)
	dl.Push(3)
	fmt.Println(dl)
	dl.Push(4, 5, 6)
	fmt.Println(dl)
	dl.SetSizeLimit(4)
	fmt.Println(dl)
	dl.FPush(10)
	fmt.Println(dl)
	fmt.Println(dl.ToSlice())
	fmt.Println(dl.At(0))
	fmt.Println(dl.At(1))
	fmt.Println(dl.At(4))
	fmt.Println(dl.At(5))
	fmt.Println(dl.FPop())
	fmt.Println(dl)
	fmt.Println(dl.At(5))
	fmt.Println(dl.At(6))
	fmt.Println(dl)
	dl.Pop()
	fmt.Println(dl)
	dl.Pop()
	fmt.Println(dl)
	dl.Pop()
	fmt.Println(dl)
	dl.Pop()
	fmt.Println(dl)
	fmt.Println(dl.Pop())
	fmt.Println(dl)
	fmt.Println(dl.Pop())
	fmt.Println(dl)
	dl.SetSizeLimit(0)
	dl.Push(1, 2, 3, 4, 5, 6)
	fmt.Println(dl)
	fmt.Println(dl.PopSlice())
	fmt.Println(dl)
	dl.Push(1, 2, 3, 4, 5)
	fmt.Println(dl.Find(func(v int) bool { return v == 3 }))
	fmt.Println(dl.FindAll(func(v int) bool { return v%2 == 0 }))
}
